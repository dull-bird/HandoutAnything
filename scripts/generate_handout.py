def classify_summary_theme(snippet: str, lang: str) -> str | None:
    """Map a snippet to a high-level theme so auto-digests stay abstract."""
    lowered = snippet.lower()
    for theme in SUMMARY_THEMES.get(lang, []):
        for keyword in theme.get("keywords", []):
            key = keyword.lower()
            if key in lowered or keyword in snippet:
                return str(theme["key"])
    return None


def theme_summary(theme_key: str, lang: str) -> tuple[str, str] | None:
    for theme in SUMMARY_THEMES.get(lang, []):
        if theme["key"] == theme_key:
            return str(theme["label"]), str(theme["summary"])
    return None


def score_snippet(snippet: str, lang: str, index: int, total: int) -> int:
    """Heuristically score a text snippet for salience."""
    lower = snippet.lower()
    score = 0
    for word in LANG_SNIPPET_KEYWORDS.get(lang, []):
        if word in lower:
            score += 3 if len(word) > 3 else 2
    if len(snippet) >= 120:
        score += 2
    elif len(snippet) >= 60:
        score += 1
    if index == 0:
        score += 1
    if index == total - 1:
        score += 1
    return score


def pick_snippets(snippets: list[str], lang: str, limit: int = 4) -> list[str]:
    """Select the most informative snippets while keeping source order."""
    normalized = [re.sub(r"\s+", " ", s).strip() for s in snippets if s and s.strip()]
    normalized = [s for s in normalized if len(s) >= 20]
    if not normalized:
        return []
    scored = [
        (score_snippet(snippet, lang, index, len(normalized)), index, snippet)
        for index, snippet in enumerate(normalized)
    ]
    scored.sort(key=lambda item: (-item[0], item[1]))
    if scored and scored[0][0] == 0:
        selected = scored[: min(limit, len(scored))]
    else:
        selected = scored[: min(limit, len(scored))]
    selected.sort(key=lambda item: item[1])
    return [snippet for _, _, snippet in selected]


def compact_snippet(snippet: str, lang: str, max_len: int = 160) -> str:
    """Trim filler and keep a transcript snippet readable as a bullet."""
    text = re.sub(r"\s+", " ", snippet).strip()
    if not text:
        return ""
    if lang == "zh":
        for prefix in [
            "这一讲",
            "这一部分",
            "我们",
            "接下来",
            "然后",
            "最后",
            "现在",
        ]:
            if text.startswith(prefix):
                text = text[len(prefix):].lstrip("，,。:：-— ")
                break
    else:
        lower = text.lower()
        for prefix in [
            "this lecture ",
            "in this lecture ",
            "in this module, ",
            "we are going to ",
            "we're going to ",
            "now ",
            "next, ",
            "finally, ",
        ]:
            if lower.startswith(prefix):
                text = text[len(prefix):].lstrip(",.:- ")
                break
    if len(text) > max_len:
        cut_points = [text.rfind(p, 0, max_len) for p in ["。", "！", "？", "；", ".", "!", "?", ";", "，", ","]]
        cut = max(cut_points)
        if cut < max_len // 2:
            cut = max_len
        text = text[:cut].rstrip()
        if not text.endswith("…"):
            text += "…"
    return text


def build_auto_digest(snippets: list[str], lang: str, label: str, intro: str, limit: int = 5) -> str:
    """Render a lecture-local auto digest block from transcript snippets."""
    selected = pick_snippets(snippets, lang, limit=limit)
    if not selected:
        return ""
    parts = [r"\begin{keyconcept}"]
    parts.append(rf"\textbf{{{tex_escape(label)}}}")
    parts.append(tex_escape(intro))
    parts.append(r"\begin{itemize}")
    for snippet in selected[:limit]:
        compact = compact_snippet(snippet, lang)
        if compact:
            parts.append(f"  \\item {tex_escape(compact)}")
    parts.append(r"\end{itemize}")
    parts.append(r"\end{keyconcept}")
    return "\n".join(parts)


def build_transcript_digest(subtitle_path: Path | None, lang: str, lecture_title: str = "") -> str:
    """Create a digest from subtitle content when hand-authored content is sparse."""
    if not subtitle_path or not subtitle_path.exists():
        return ""
    raw_text = subtitle_path.read_text(encoding="utf-8", errors="replace")
    if lang == "en" and contains_cjk(raw_text):
        raise SystemExit(f"English output requires English subtitle text: {subtitle_path.name}")
    if subtitle_path.suffix.lower() == ".vtt":
        snippets = parse_vtt_cues(subtitle_path)
    else:
        snippets = split_text_units(raw_text, lang)
    if lecture_title:
        label = f"{lecture_title} 的字幕要点" if lang == "zh" else f"{lecture_title} transcript notes"
    else:
        label = "字幕要点" if lang == "zh" else "Transcript notes"
    intro = (
        "根据字幕自动提炼，这一讲再补充几条最值得记住的线索。"
        if lang == "zh"
        else "Expanded automatically from the transcript to keep the lecture's main lines visible."
    )
    return build_auto_digest(snippets, lang, label, intro)


def build_pdf_digest(pdf_path: Path | None, lang: str, resource_name: str = "") -> str:
    """Create a digest from supplementary PDF text when no hand-authored summary exists."""
    if not pdf_path or not pdf_path.exists():
        return ""
    if lang == "en" and resource_name and not display_resource_name(resource_name, pdf_path, lang):
        return ""
    extracted = extract_pdf_text(pdf_path, max_pages=4)
    if not extracted or extracted.startswith("[PDF extraction failed"):
        return ""
    if lang == "en" and not is_likely_english_text(extracted):
        return ""
    snippets = split_text_units(extracted, lang)
    label = "补充材料要点" if lang == "zh" else "Reading notes"
    intro = (
        "根据补充材料自动提炼，这份阅读再补几条关键线索。"
        if lang == "zh"
        else "Expanded automatically from the extracted PDF text to surface the main points."
    )
    return build_auto_digest(snippets, lang, label, intro, limit=3)


def render_text_box(title: str, lines: list[str]) -> str:
    """Render a compact framed box with monospaced multi-line content."""
    cleaned = [line.rstrip() for line in lines if line and line.strip()]
    if not cleaned:
        return ""
    body = r"\\ ".join(tex_escape(line) for line in cleaned)
    return "\n".join(
        [
            r"\begin{center}",
            r"\fcolorbox{darkgray}{white}{%",
            r"\begin{minipage}{0.94\linewidth}",
            rf"\textbf{{{tex_escape(title)}}}\\[0.35em]",
            r"\ttfamily\small",
            body,
            r"\end{minipage}}",
            r"\end{center}",
        ]
    )


def normalize_plain_items(value) -> list[str]:
    """Flatten a value into a clean list of plain-text items."""
    if value is None:
        return []
    if isinstance(value, str):
        text = re.sub(r"\s+", " ", value).strip()
        return [text] if text else []
    if isinstance(value, dict):
        items: list[str] = []
        for key in ("summary", "lead", "body", "text", "key_points", "bullets", "diagram", "visual_notes", "discussion"):
            if key in value:
                items.extend(normalize_plain_items(value[key]))
        return items
    if isinstance(value, (list, tuple)):
        items: list[str] = []
        for item in value:
            items.extend(normalize_plain_items(item))
        return items
    text = re.sub(r"\s+", " ", str(value)).strip()
    return [text] if text else []


def normalize_line_items(value) -> list[str]:
    """Flatten a value into lines, preserving explicit line breaks when present."""
    if isinstance(value, str):
        lines = [line.strip() for line in value.splitlines() if line.strip()]
        if lines:
            return lines
    return normalize_plain_items(value)


def collect_visible_text(value) -> str:
    """Collect all text fragments from a structured block for length checks."""
    return " ".join(normalize_plain_items(value))


def render_itemize_box(title: str, items: list[str]) -> str:
    """Render a framed bullet list box."""
    cleaned = [item.strip() for item in items if item and item.strip()]
    if not cleaned:
        return ""
    parts = [r"\begin{keyconcept}", rf"\textbf{{{tex_escape(title)}}}", r"\begin{itemize}"]
    for item in cleaned:
        parts.append(f"  \\item {tex_escape(item)}")
    parts.append(r"\end{itemize}")
    parts.append(r"\end{keyconcept}")
    return "\n".join(parts)


def render_content_block(block, lang: str) -> str:
    """Render a lecture or unit content block in either legacy or structured form."""
    if not block:
        return ""
    if isinstance(block, str):
        return block
    if isinstance(block, list):
        paragraphs = [part for part in normalize_plain_items(block)]
        return "\n\n".join(paragraphs)
    if not isinstance(block, dict):
        return tex_escape(str(block))

    parts: list[str] = []
    summary = block.get("summary") or block.get("body") or block.get("text")
    if summary:
        if isinstance(summary, str):
            parts.append(summary)
        else:
            summary_parts = [part for part in normalize_plain_items(summary)]
            if summary_parts:
                parts.append("\n\n".join(summary_parts))

    key_points = block.get("key_points") or block.get("bullets")
    if key_points:
        parts.append(render_itemize_box(block.get("key_points_title", ""), normalize_plain_items(key_points)))

    diagram = block.get("diagram")
    if diagram:
        title = block.get("diagram_title") or get_text(lang, "diagram")
        parts.append(render_text_box(title, normalize_line_items(diagram)))

    visual_notes = block.get("visual_notes") or block.get("frame_notes")
    if visual_notes:
        title = block.get("visual_notes_title") or get_text(lang, "visual_notes")
        parts.append(render_itemize_box(title, normalize_line_items(visual_notes)))

    discussion = block.get("discussion")
    if discussion:
        title = block.get("discussion_title") or get_text(lang, "discussion")
        parts.append(render_itemize_box(title, normalize_line_items(discussion)))

    extra = block.get("extra")
    if extra:
        parts.append(render_content_block(extra, lang))

    return "\n\n".join(part for part in parts if part)


def block_visible_len(block) -> int:
    """Estimate visible text length for strings or structured content blocks."""
    return visible_text_len(collect_visible_text(block))


def tex_escape(text: str) -> str:
    """Escape special LaTeX characters."""
    return (
        text.replace("\\", r"\textbackslash{}")
        .replace("&", r"\&")
        .replace("%", r"\%")
        .replace("$", r"\$")
        .replace("#", r"\#")
        .replace("_", r"\_")
        .replace("{", r"\{")
        .replace("}", r"\}")
        .replace("~", r"\textasciitilde{}")
        .replace("^", r"\textasciicircum{}")
    )


# ── Handout generation ────────────────────────────────────────────────────────

def generate_handout(
    data_dir: Path,
    course_title: str,
    unit_title: str,
    instructor: str,
    output: Path,
    course_title_en: str = "",
    unit_title_en: str = "",
    lang: str = "zh",
    insert_keyframes: bool = False,
):
    """Generate a complete LaTeX handout."""

    if lang not in TEXT:
        raise SystemExit(f"unsupported language: {lang}")

    display_course_title = course_title if lang == "zh" else (course_title_en or course_title)
    display_unit_title = unit_title if lang == "zh" else (unit_title_en or unit_title)
    if lang == "en" and (contains_cjk(display_course_title) or contains_cjk(display_unit_title)):
        raise SystemExit(
            "English output requires English course and unit titles; pass --course-title-en and --unit-title-en"
        )

    # Load manifest
    manifest_path = data_dir / "manifest.json"
    if not manifest_path.exists():
        print(f"Error: {manifest_path} not found", file=sys.stderr)
        sys.exit(1)

    manifest = json.loads(manifest_path.read_text(encoding="utf-8"))

    # Load keyframes
    keyframes_path = data_dir / "keyframes.json"
    keyframes = []
    if keyframes_path.exists():
        keyframes = json.loads(keyframes_path.read_text(encoding="utf-8"))

    # Build LaTeX
    tex = []

    tex.append(build_preamble(lang, display_course_title, display_unit_title, instructor, data_dir))
    tex.append(build_title_page(lang, course_title, unit_title, instructor, course_title_en, unit_title_en))
    tex.append(build_toc(lang))

    # ── Load content.json (language-aware) ──
    content_json_path = data_dir / ("content_en.json" if lang == "en" else "content.json")
    if content_json_path.exists():
        content_data = json.loads(content_json_path.read_text(encoding="utf-8"))
    else:
        content_data = {}
    lecture_titles = content_data.get("lecture_titles", {})

    # ── Knowledge Map ──
    knowledge_map = content_data.get("knowledge_map", [])
    if knowledge_map:
        tex.append(rf"\section*{{{get_text(lang, 'knowledge_map')}}}")
        tex.append(add_toc_entry("section", get_text(lang, "knowledge_map")))
        tex.append(r"\begin{longtable}{p{3.1cm}p{10.2cm}}")
        tex.append(r"\toprule")
        tex.append(rf"{get_text(lang, 'knowledge_topic')} & {get_text(lang, 'knowledge_question')} \\")
        tex.append(r"\midrule")
        for row in knowledge_map:
            topic = row.get("topic", "")
            question = row.get("question", "")
            tex.append(f"{topic} & {question} \\\\")
        tex.append(r"\bottomrule")
        tex.append(r"\end{longtable}")
        tex.append("")

    # ── Section 0: Overview ──
    overview = content_data.get("overview", "")
    tex.append(rf"\section*{{{get_text(lang, 'overview')}}}")
    tex.append(add_toc_entry("section", get_text(lang, "overview")))
    if overview:
        tex.append(render_content_block(overview, lang))
    else:
        tex.append(
            r"This unit covers the core concepts of the course."
            if lang == "en"
            else r"本单元涵盖课程的核心概念。"
        )
    tex.append("")

    # ── Per-lecture sections ──
    lecture_summaries = content_data.get("lectures", {})
    for i, item in enumerate(manifest):
        subtitle_path = resolve_subtitle_path(data_dir, item)
        video_stem_key = item.get("video", "").replace(".mp4", "") if item.get("video") else ""
        vtt_source_name = subtitle_path.stem if subtitle_path else item.get("en_vtt", item.get("vtt", "")).replace(".vtt", "")
        vtt_stem_key = re.sub(r"\.(en|zh-CN|zh-TW|ja|ko|fr|de|es|pt|ar)$", "", vtt_source_name)
        lecture_title = item["title"]
        if lang == "en":
            lecture_title = (
                lecture_titles.get(video_stem_key)
                or lecture_titles.get(vtt_stem_key)
                or item.get("title_en")
                or item.get("title")
            )
            if contains_cjk(lecture_title):
                raise SystemExit(
                    "English output requires English lecture titles in manifest.json or content_en.json"
                )
        section_num = i + 1

        tex.append(f"\\section*{{{section_num}. {tex_escape(lecture_title)}}}")
        tex.append(add_toc_entry("section", f"{section_num}. {lecture_title}"))

        # Video link with duration
        video_url = item.get("page_url", "")
        duration = item.get("duration", "")
        dur_str = f"({duration})" if lang == "en" and duration else f"（{duration}）" if duration else ""
        if video_url:
            tex.append(
                rf"\noindent\textbf{{{get_text(lang, 'lesson_review')}}}\videolink{{{video_url}}}{{{tex_escape(lecture_title)}}}{dur_str}"
            )
        tex.append("")

        # Per-lecture content from content.json
        lecture_content = lecture_summaries.get(video_stem_key) or lecture_summaries.get(vtt_stem_key) or ""
        auto_lecture_content = build_transcript_digest(subtitle_path, lang, lecture_title)
        if lecture_content:
            tex.append(render_content_block(lecture_content, lang))
            if block_visible_len(lecture_content) < 420 and auto_lecture_content:
                tex.append("")
                tex.append(auto_lecture_content)
        elif auto_lecture_content:
            tex.append(auto_lecture_content)
        else:
            if lang == "en":
                tex.append("This lecture summary should be added to content_en.json.")
            else:
                tex.append("这一讲的总结尚未补齐，可先从字幕中提炼主线。")
            tex.append("")
        tex.append("")

        # Supplementary materials
        if item.get("resources"):
            supplements_path = data_dir / ("supplements_en.json" if lang == "en" else "supplements.json")
            supplements_data = {}
            if supplements_path.exists():
                supplements_data = json.loads(supplements_path.read_text(encoding="utf-8"))
            for res_name in item["resources"]:
                res_path = resolve_existing_path(data_dir, res_name)
                if res_name in supplements_data:
                    info = supplements_data[res_name]
                    tex.append(f"\\textbf{{📎 {info['title']}}}")
                    escaped_name = tex_escape(res_name)
                    tex.append(f"\\hfill{{\\small\\texttt{{{escaped_name}}}}}")
                    tex.append("")
                    tex.append(rf"\begin{{supplement}}{{{get_text(lang, 'supplement_summary')}}}")
                    tex.append(r"\begin{itemize}")
                    for para in info.get("summary", []):
                        tex.append(f"  \\item {para}")
                    tex.append(r"\end{itemize}")
                    if visible_text_len("\n".join(info.get("summary", []))) < 260:
                        auto_supplement = build_pdf_digest(res_path, lang, res_name)
                        if auto_supplement:
                            tex.append("")
                            tex.append(auto_supplement)
                    tex.append(r"\end{supplement}")
                    tex.append("")
                else:
                    sep = ":" if lang == "en" else "："
                    display_name = display_resource_name(res_name, res_path, lang)
                    line = f"\\textbf{{{get_text(lang, 'supplement_label')}}}{sep}"
                    if display_name:
                        line += f"\\texttt{{{tex_escape(display_name)}}}"
                    tex.append(line)
                    auto_supplement = build_pdf_digest(res_path, lang, res_name)
                    if auto_supplement:
                        tex.append(auto_supplement)
                    tex.append("")

        # Keyframes (optional)
        if insert_keyframes:
            video_stem = item.get("video", "").replace(".mp4", "") if item.get("video") else ""
            lecture_frames = [kf for kf in keyframes if (video_stem and video_stem in kf.get("video", "")) or (vtt_stem_key and vtt_stem_key in kf.get("vtt", ""))]
            if lecture_frames:
                for kf in lecture_frames[:2]:
                    time_label = f"{int(kf['time']):04d}s" if kf['time'] < 60 else f"{int(kf['time'])//60:02d}m{int(kf['time'])%60:02d}s"
                    frame_file = f"{vtt_stem_key}_{time_label}_{kf['reason']}.png"
                    frame_path = data_dir / "frames" / frame_file
                    if frame_path.exists():
                        reason_label = get_text(lang, "keyframe_reason").get(kf["reason"], kf["reason"])
                        caption = get_text(lang, "keyframe_caption").format(time=int(kf["time"]), reason=reason_label)
                        tex.append(f"\\keyframe{{{frame_file}}}{{{caption}}}")
        tex.append("")

    # ── Unit synthesis / discussion ──
    next_section_num = len(manifest) + 1
    synthesis = content_data.get("synthesis", "")
    if synthesis:
        section_title = f"{next_section_num}. {get_text(lang, 'synthesis')}"
        tex.append(rf"\section*{{{section_title}}}")
        tex.append(add_toc_entry("section", section_title))
        tex.append(render_content_block(synthesis, lang))
        tex.append("")
        next_section_num += 1

    discussion = content_data.get("discussion", "")
    if discussion:
        section_title = f"{next_section_num}. {get_text(lang, 'discussion')}"
        tex.append(rf"\section*{{{section_title}}}")
        tex.append(add_toc_entry("section", section_title))
        tex.append(render_content_block(discussion, lang))
        tex.append("")
        next_section_num += 1

    # ── Key Takeaways ──
    key_takeaways = content_data.get("key_takeaways", [])
    if key_takeaways:
        takeaway_num = next_section_num
        if lang == "en":
            section_title = f"{takeaway_num}. {get_text(lang, 'key_takeaways')}"
            tex.append(rf"\section*{{{section_title}}}")
            tex.append(add_toc_entry("section", section_title))
        else:
            n = len(key_takeaways)
            cn_num = {3: "三", 4: "四", 5: "五", 6: "六", 7: "七", 8: "八", 9: "九", 10: "十"}.get(n, str(n))
            section_title = f"{takeaway_num}. {get_text(lang, 'key_takeaways').format(count=cn_num)}"
            tex.append(rf"\section*{{{section_title}}}")
            tex.append(add_toc_entry("section", section_title))
        tex.append(r"\begin{enumerate}")
        for t in key_takeaways:
            tex.append(f"  \\item {t}")
        tex.append(r"\end{enumerate}")
        tex.append("")
        next_section_num += 1

    # ── Exercises ──
    exercises = content_data.get("exercises", {})
    answers = content_data.get("answers", {})
    if exercises:
        ex_num = next_section_num
        section_title = f"{ex_num}. {get_text(lang, 'exercises')}"
        tex.append(rf"\section*{{{section_title}}}")
        tex.append(add_toc_entry("section", section_title))

        # A. Multiple choice
        choice = exercises.get("choice", [])
        if choice:
            tex.append(rf"\subsection*{{A. {get_text(lang, 'mcq').format(count=len(choice))}}}")
            tex.append(r"\begin{enumerate}")
            for q in choice:
                tex.append(f"  \\item {q['q']}\\\\")
                options = " \\quad ".join(q.get("options", []))
                tex.append(f"  {options}")
                tex.append("")
            tex.append(r"\end{enumerate}")
            tex.append("")

        # B. True/False
        truefalse = exercises.get("truefalse", [])
        if truefalse:
            tex.append(rf"\subsection*{{B. {get_text(lang, 'truefalse').format(count=len(truefalse))}}}")
            tex.append(r"\begin{enumerate}")
            for q in truefalse:
                tex.append(f"  \\item {q}(\\quad)" if lang == "en" else f"  \\item {q}（\\quad）")
            tex.append(r"\end{enumerate}")
            tex.append("")

        # C. Short answer
        shortanswer = exercises.get("shortanswer", [])
        if shortanswer:
            tex.append(rf"\subsection*{{C. {get_text(lang, 'shortanswer').format(count=len(shortanswer))}}}")
            tex.append(r"\begin{enumerate}")
            for q in shortanswer:
                tex.append(f"  \\item {q}")
            tex.append(r"\end{enumerate}")
            tex.append("")
        next_section_num += 1

    # ── Answers ──
    if answers:
        ans_num = next_section_num
        section_title = f"{ans_num}. {get_text(lang, 'answers')}"
        tex.append(rf"\section*{{{section_title}}}")
        tex.append(add_toc_entry("section", section_title))

        if answers.get("choice"):
            tex.append(rf"\subsection*{{{get_text(lang, 'mcq_answers')}}}")
            tex.append(answers["choice"])
            tex.append("")

        if answers.get("truefalse"):
            tex.append(rf"\subsection*{{{get_text(lang, 'truefalse_answers')}}}")
            tex.append(answers["truefalse"])
            tex.append("")

        if answers.get("shortanswer"):
            tex.append(rf"\subsection*{{{get_text(lang, 'shortanswer_answers')}}}")
            tex.append(r"\begin{enumerate}")
            for a in answers["shortanswer"]:
                tex.append(f"  \\item {a}")
            tex.append(r"\end{enumerate}")
            tex.append("")

    # End document
    tex.append(r"\end{document}")
    
    # Write output
    output.write_text("\n".join(tex), encoding="utf-8")
    print(f"Generated: {output}")
    print(f"  Lectures: {len(manifest)}")
    print(f"  Keyframes: {len(keyframes)}")
    print(f"  Compile with: xelatex {output.name} && xelatex {output.name}")


