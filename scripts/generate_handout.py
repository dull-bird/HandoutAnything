def get_text(lang: str, key: str) -> str:
    return TEXT[lang][key]


def contains_cjk(text: str) -> bool:
    return bool(re.search(r"[\u4e00-\u9fff]", text))


def is_likely_english_text(text: str) -> bool:
    """Heuristic filter for extracted text that should stay in English mode."""
    alpha_total = sum(1 for ch in text if ch.isalpha())
    if not alpha_total:
        return False
    ascii_alpha = sum(1 for ch in text if ch.isascii() and ch.isalpha())
    if contains_cjk(text):
        return False
    return ascii_alpha >= 20 and ascii_alpha / alpha_total >= 0.85


def display_resource_name(res_name: str, res_path: Path | None, lang: str) -> str:
    """Return a readable resource label, hiding non-English names in English mode."""
    candidate = ""
    if res_path and res_path.stem:
        candidate = res_path.stem
    elif res_name:
        candidate = Path(res_name).stem
    candidate = candidate.replace("_", " ").strip()
    candidate = re.sub(r"^\d+\s*", "", candidate)
    candidate = re.sub(r"\s+", " ", candidate).strip()
    if not candidate:
        return ""
    if lang == "en" and (contains_cjk(candidate) or not re.search(r"[A-Za-z]", candidate)):
        return ""
    return candidate


